const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ctx = vm.createContext({});
vm.runInContext(fs.readFileSync('tage/scripts/2.js', 'utf8').replaceAll('export function', 'function'), ctx);
const rows = Array.from({length:5}, () => ({}));
assert.equal(ctx.isComplete(rows), false);
ctx.assignItem(rows, 0, 'coat', 2);
ctx.assignItem(rows, 1, 'coat', 2);
assert.equal(rows[0].coat, undefined);
assert.equal(rows[1].coat, 2);
for (let i=0;i<5;i++) for (const group of ['coat','bag','ticket']) ctx.assignItem(rows,i,group,i);
assert.equal(ctx.isCorrect(rows), true);
const restored = JSON.parse(JSON.stringify(rows));
assert.equal(ctx.isCorrect(restored), true);
ctx.assignItem(rows,0,'bag',1);
assert.equal(ctx.isComplete(rows), false);
ctx.assignItem(rows,1,'bag',0);
assert.equal(ctx.isComplete(rows), true);
assert.equal(ctx.isCorrect(rows), false);
console.log('OK: unique ownership, reassignment, incomplete and incorrect answers, correct solution, persisted state.');

const shuffled = ctx.shuffledItems(() => 0);
assert.equal(ctx.validOrder(shuffled), true);
assert.notDeepEqual(Array.from(shuffled), [0,1,2,3,4]);
assert.equal(ctx.validOrder([0,0,2,3,4]), false);
assert.equal(ctx.validOrder([0,1,2,3,5]), false);
assert.equal(ctx.validOrder(null), false);
assert.equal(ctx.isCorrect(restored), true);
console.log('OK: shuffled display contains each item once; invalid saved orders rejected; answer identities unchanged.');
